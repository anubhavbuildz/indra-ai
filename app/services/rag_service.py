"""FAISS index construction, validation, persistence, and retrieval."""

import os
import pickle
import tempfile
from pathlib import Path
from typing import Any

from app.core.config import Settings
from app.core.errors import AppError
from app.services.embedding_service import (
    EMBEDDING_DIMENSION,
    EMBEDDING_MODEL_ID,
    EmbeddingService,
)

SCHEMA_VERSION = 1
METADATA_FIELDS = {
    "chunk_id",
    "text",
    "source_title",
    "source_url",
    "document_version",
    "document_date",
    "section_id",
}


class RagService:
    """Read-only retrieval service over a locally generated FAISS/pickle pair."""

    def __init__(self, settings: Settings) -> None:
        self.settings = settings
        self.embeddings = EmbeddingService(settings.embedding_model)

    def _load(self) -> tuple[Any, dict[str, Any]] | None:
        index_path = self.settings.faiss_index_path
        metadata_path = self.settings.faiss_metadata_path
        if not index_path.is_file() or not metadata_path.is_file():
            return None
        try:
            import faiss

            # This file is trusted only because it is locally generated by the ingestion script.
            with metadata_path.open("rb") as metadata_file:
                metadata = pickle.load(metadata_file)
            index = faiss.read_index(str(index_path))
        except (OSError, EOFError, pickle.UnpicklingError, RuntimeError, ValueError) as exc:
            raise AppError(503, "rag_index_unavailable", "The local retrieval index is unavailable.") from exc

        if not isinstance(metadata, dict):
            raise AppError(503, "rag_index_mismatch", "The retrieval index metadata is incompatible.")
        documents = metadata.get("documents")
        if (
            metadata.get("schema_version") != SCHEMA_VERSION
            or metadata.get("dimension") != EMBEDDING_DIMENSION
            or metadata.get("embedding_model") != self.embeddings.model_id
            or not isinstance(documents, list)
            or index.d != EMBEDDING_DIMENSION
            or index.ntotal != len(documents)
            or any(
                not isinstance(item, dict)
                or not METADATA_FIELDS.issubset(item)
                or any(not isinstance(item[key], str) for key in METADATA_FIELDS)
                or not item["chunk_id"]
                or not item["text"]
                or not item["source_title"]
                for item in documents
            )
            or len({item["chunk_id"] for item in documents if isinstance(item, dict)}) != len(documents)
        ):
            raise AppError(503, "rag_index_mismatch", "The retrieval index metadata is incompatible.")
        return index, metadata

    def status(self) -> dict[str, Any]:
        try:
            loaded = self._load()
        except AppError as exc:
            state = "mismatch" if exc.code == "rag_index_mismatch" else "unavailable"
            return {
                "status": state,
                "indexed_passages": 0,
                "dimension": None,
                "embedding_model": None,
            }
        if loaded is None:
            return {
                "status": "not_indexed",
                "indexed_passages": 0,
                "dimension": None,
                "embedding_model": None,
            }
        index, metadata = loaded
        return {
            "status": "ready",
            "indexed_passages": index.ntotal,
            "dimension": index.d,
            "embedding_model": metadata["embedding_model"],
        }

    def query(self, text: str, limit: int = 5) -> dict[str, Any]:
        try:
            loaded = self._load()
        except AppError as exc:
            state = "mismatch" if exc.code == "rag_index_mismatch" else "unavailable"
            return {"status": state, "results": []}
        if loaded is None:
            return {"status": "not_indexed", "results": []}

        import numpy as np

        index, metadata = loaded
        vector = np.asarray([self.embeddings.embed(text)], dtype="float32")
        scores, indices = index.search(vector, min(limit, index.ntotal))
        results = []
        for score, document_index in zip(scores[0], indices[0], strict=True):
            if document_index < 0:
                continue
            results.append({"score": float(score), **metadata["documents"][int(document_index)]})
        return {"status": "ready", "results": results}


def build_index(settings: Settings, documents: list[dict[str, str]]) -> int:
    """Build and atomically replace a matching FAISS index and trusted metadata file."""
    if not documents:
        raise ValueError("At least one document chunk is required to build the index.")
    for document in documents:
        if (
            not METADATA_FIELDS.issubset(document)
            or any(not isinstance(document.get(key), str) for key in METADATA_FIELDS)
            or not document["chunk_id"]
            or not document["text"]
            or not document["source_title"]
        ):
            raise ValueError("Each chunk must include all source attribution fields.")
    if len({document["chunk_id"] for document in documents}) != len(documents):
        raise ValueError("Chunk identifiers must be unique within an index.")
    try:
        import faiss
        import numpy as np
    except ImportError as exc:
        raise RuntimeError("FAISS and NumPy are required to build the retrieval index.") from exc

    embeddings = EmbeddingService(settings.embedding_model)
    vectors = np.asarray([embeddings.embed(item["text"]) for item in documents], dtype="float32")
    index = faiss.IndexFlatIP(EMBEDDING_DIMENSION)
    index.add(vectors)
    index_path = settings.faiss_index_path
    metadata_path = settings.faiss_metadata_path
    index_path.parent.mkdir(parents=True, exist_ok=True)
    metadata_path.parent.mkdir(parents=True, exist_ok=True)
    metadata: dict[str, Any] = {
        "schema_version": SCHEMA_VERSION,
        "dimension": EMBEDDING_DIMENSION,
        "embedding_model": embeddings.model_id,
        "documents": documents,
    }
    index_fd, index_temp_name = tempfile.mkstemp(dir=index_path.parent, prefix=".index-")
    metadata_fd, metadata_temp_name = tempfile.mkstemp(dir=metadata_path.parent, prefix=".metadata-")
    os.close(index_fd)
    os.close(metadata_fd)
    try:
        faiss.write_index(index, index_temp_name)
        with open(metadata_temp_name, "wb") as metadata_file:
            pickle.dump(metadata, metadata_file, protocol=pickle.HIGHEST_PROTOCOL)
        os.replace(index_temp_name, index_path)
        os.replace(metadata_temp_name, metadata_path)
    finally:
        Path(index_temp_name).unlink(missing_ok=True)
        Path(metadata_temp_name).unlink(missing_ok=True)
    return index.ntotal
